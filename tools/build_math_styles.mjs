// Match the native math renderer, including font assets for offline reading.
import fs from 'node:fs/promises';
const dir=new URL('../node_modules/katex/dist/',import.meta.url);
let css=await fs.readFile(new URL('katex.min.css',dir),'utf8');
const pattern=/src:url\(fonts\/([^)]*\.woff2)\) format\("woff2"\)(?:,url\([^)]+\) format\("[^"]+"\))*/g;
const fonts=new Map();
for(const match of css.matchAll(pattern)) {
  const bytes=await fs.readFile(new URL('fonts/'+match[1],dir));
  fonts.set(match[1],bytes.toString('base64'));
}
css=css.replace(pattern,(_,name)=>`src:url("data:font/woff2;base64,${fonts.get(name)}") format("woff2")`);
const custom=await fs.readFile(new URL('../styles/standards.css',import.meta.url),'utf8');
await fs.writeFile(new URL('../styles/reader.css',import.meta.url),'/* Generated by tools/build_math_styles.mjs. Edit standards.css. */\n'+css+'\n'+custom);
await fs.copyFile(new URL('../node_modules/katex/LICENSE',import.meta.url),new URL('../styles/KaTeX-LICENSE.txt',import.meta.url));
